"use strict";

// config/stable_tool_manifest.json is the tool-contract SSOT shared by the MCP
// servers and this compactor. The generated module is checked in (like the
// design guidance bundle) so installed bundles need no repo path at runtime.
const fs = require("node:fs");
const path = require("node:path");

const EFFECTS = new Set(["read", "ephemeral", "mutation", "long_running"]);
const OBSERVATION_EFFECTS = new Set(["read"]);
const RESULT_KINDS = new Set(["source_body", "search_hits", "archive_page", "validation", "metadata", "proposal", "mutation_result"]);
function capabilityData(manifest) {
  const providers = manifest.capabilityProviders;
  const data = {};
  for (const [provider, descriptor] of Object.entries(providers || {})) {
    const effects = manifest[descriptor.effects], operations = manifest.operationContracts?.[provider];
    if (!operations || Object.keys(effects).length !== Object.keys(operations).length) throw Error(`Operation coverage drift: ${provider}`);
    const contract = (effect, op, label) => {
      if (!EFFECTS.has(effect) || !RESULT_KINDS.has(op?.resultKind)) throw Error(`Invalid capability: ${label}`);
      if (op.minimumEnvelopeChars !== undefined && (!Number.isSafeInteger(op.minimumEnvelopeChars) || op.minimumEnvelopeChars < 1)) throw Error(`Invalid minimum: ${label}`);
      return {...op,effect,scope:descriptor.scope};
    };
    data[provider] = Object.fromEntries(Object.entries(effects).map(([name,effect])=> {
      const op=operations[name];
      if(typeof effect==='string') return [name,contract(effect,op,`${provider}/${name}`)];
      if(!op?.actions || Object.keys(effect).length!==Object.keys(op.actions).length) throw Error(`Action coverage drift: ${name}`);
      return [name,{actions:Object.fromEntries(Object.entries(effect).map(([action,e])=>[action,contract(e,op.actions[action],`${name}/${action}`)]))}];
    }));
  }
  if (!Object.keys(data).length) throw Error("Missing capability providers");
  return data;
}
function renderData(manifest) {
  return '// Generated by scripts/build-tool-contract.cjs. Do not edit.\n"use strict";\n'
    + `module.exports = { TOOL_CAPABILITIES: ${JSON.stringify(capabilityData(manifest))} };\n`;
}

function observationNames(effects, label) {
  if (!effects || typeof effects !== "object") throw new Error(`Manifest is missing ${label}`);
  for (const [name, effect] of Object.entries(effects)) {
    if (!EFFECTS.has(effect)) throw new Error(`Invalid effect for ${label}.${name}: ${effect}`);
  }
  return Object.keys(effects).filter(name => OBSERVATION_EFFECTS.has(effects[name])).sort();
}

const mutationNames = effects => Object.keys(effects).filter(name => effects[name] === "mutation").sort();

function renderContract(manifest) {
  capabilityData(manifest);
  const agent = observationNames(manifest.agentToolEffects, "agentToolEffects");
  const rag = observationNames(manifest.ragToolEffects, "ragToolEffects");
  const contracts = manifest.readResultContracts;
  if (!contracts || typeof contracts !== "object") throw new Error("Manifest is missing readResultContracts");
  const { description: _description, ...readResultContracts } = contracts;
  return "// Generated by scripts/build-tool-contract.cjs from config/stable_tool_manifest.json. Do not edit.\n"
    + 'export { TOOL_CAPABILITIES } from "./generated-tool-capability-data.js";\n'
    + `export const UNREAL_AGENT_OBSERVATION_TOOL_NAMES: readonly string[] = ${JSON.stringify(agent)};\n`
    + `export const UNREAL_RAG_OBSERVATION_TOOL_NAMES: readonly string[] = ${JSON.stringify(rag)};\n`
    + `export const UNREAL_AGENT_MUTATION_TOOL_NAMES: readonly string[] = ${JSON.stringify(mutationNames(manifest.agentToolEffects))};\n`
    + `export const UNREAL_RAG_MUTATION_TOOL_NAMES: readonly string[] = ${JSON.stringify(mutationNames(manifest.ragToolEffects))};\n`
    + "export const READ_RESULT_CONTRACTS: Readonly<{ nativeByteTools: Record<string, string[]>; "
    + "byteBudgetDefaults: Record<string, number>; toolDefaults: Record<string, number>; fieldDefault: number; "
    + `maxBytesCeiling: number }> = ${JSON.stringify(readResultContracts)};\n`;
}

function main() {
  const pluginRoot = path.resolve(__dirname, "..");
  const manifestPath = path.resolve(pluginRoot, "../config/stable_tool_manifest.json");
  const output = path.join(pluginRoot, "src/generated-tool-contract.ts");
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8").replace(/^﻿/, ""));
  const unity = { ...require("../../lmstudio-unity-mcp/src/catalog").toolEffects,
    ...Object.fromEntries(require("../../shared-tool-core/workspace").workspaceToolDefinitions().map(t=>[t.name,"read"])) };
  if (!require("node:util").isDeepStrictEqual(unity, manifest.unityToolEffects)) throw Error("Unity server effects differ from stable manifest");
  const content = renderContract(manifest);
  const outputs = [[output, content], [path.join(pluginRoot, "src/generated-tool-capability-data.js"), renderData(manifest)]];
  for (const [output, content] of outputs) {
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== content)
      throw new Error("Generated tool contract is stale; run npm run toolcontract:build");
  } else fs.writeFileSync(output, content);
  }
}

if (require.main === module) main();
module.exports = { renderContract, renderData, capabilityData };
