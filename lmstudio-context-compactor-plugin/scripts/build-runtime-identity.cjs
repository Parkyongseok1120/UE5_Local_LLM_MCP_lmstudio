"use strict";
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
function renderIdentity(root) {
  const files = [];
  function visit(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(file);
      else if (entry.isFile() && entry.name !== "generated-runtime-identity.ts") files.push(file);
    }
  }
  visit(path.join(root, "src"));
  visit(path.join(root, "scripts"));
  for (const name of ["manifest.json", "package.json", "package-lock.json", "tsconfig.json"])
    files.push(path.join(root, name));
  const digest = crypto.createHash("sha256");
  for (const file of files.sort()) {
    digest.update(path.relative(root, file).replaceAll("\\", "/")); digest.update("\0");
    digest.update(fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n")); digest.update("\0");
  }
  return "// Generated by scripts/build-runtime-identity.cjs; excludes this generated file.\n"
    + `export const LOADED_BUILD_ID = "ef-build-v2-${digest.digest("hex")}";\n`;
}
function main() {
  const root = path.resolve(__dirname, ".."), file = path.join(root, "src/generated-runtime-identity.ts");
  const content = renderIdentity(root);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== content)
      throw new Error("Runtime build identity is stale; run npm run identity:build");
  } else fs.writeFileSync(file, content);
}
if (require.main === module) main();
module.exports = { renderIdentity };
