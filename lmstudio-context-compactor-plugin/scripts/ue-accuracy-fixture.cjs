function fixtureFile(filePath, lines, kind = "source") {
  const content = lines.join("\n");
  return {
    path: filePath,
    kind,
    lines,
    content,
    sha256: crypto.createHash("sha256").update(content, "utf8").digest("hex"),
  };
}

